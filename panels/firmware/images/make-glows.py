"""Soft glows for the panel screens as LVGL A8 images (alpha only, coloured on
the panel). Run from panels/firmware/images with Pillow (panels/.venv);
writes ../main/images/glow_*.c. Small images, shown scaled up 2x: smooth anyway.
"""

import math
from pathlib import Path

from PIL import Image

OUT = Path(__file__).resolve().parent.parent / "main" / "images"


def falloff(d: float) -> float:
    """A gaussian: soft all the way out, without a visible edge."""
    return math.exp(-2.4 * d * d) if d < 1.6 else 0.0


def glow(width: int, height: int, cx: float, cy: float, rx: float, ry: float) -> Image.Image:
    img = Image.new("L", (width, height))
    px = img.load()
    for y in range(height):
        for x in range(width):
            d = math.hypot((x - cx) / rx, (y - cy) / ry)
            px[x, y] = round(255 * falloff(d))
    return img


def write(name: str, img: Image.Image) -> None:
    w, h = img.size
    data = img.tobytes()
    rows = ",\n".join("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24])
                      for i in range(0, len(data), 24))
    OUT.mkdir(exist_ok=True)
    (OUT / f"{name}.c").write_text(f"""/* Generated by panels/firmware/images/make-glows.py: an alpha-only glow. */
#include "lvgl.h"

static const uint8_t {name}_map[] = {{
{rows}
}};

const lv_image_dsc_t {name} = {{
    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .w = {w}, .h = {h}, .stride = {w}}},
    .data_size = sizeof({name}_map),
    .data = {name}_map,
}};
""")
    print(f"{name}: {w} x {h}")


# Light falling from the top edge (the sky), over the top two thirds.
# Sized so the light has faded to under 1 % where the image ends: no edge.
write("glow_sky", glow(360, 260, 180, -30, 260, 200))
# A round glow behind the time.
write("glow_round", glow(160, 160, 80, 80, 50, 50))
