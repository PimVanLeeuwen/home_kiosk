"""The outside services' logos for the panels as LVGL A8 images (alpha only, coloured
on the panel), from the hub's bundled Simple Icons (web/src/lib/brandLogos.ts, CC0),
with their glow colours. Needs rsvg-convert (Homebrew librsvg) and Pillow
(panels/.venv). Run from panels/firmware/images; writes ../main/images/logos.c.
"""

import re
import subprocess
from io import BytesIO
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
SOURCE = HERE.parents[2] / "web" / "src" / "lib" / "brandLogos.ts"
OUT = HERE.parent / "main" / "images" / "logos.c"
SIZE = 48  # drawn at 28 to 48 px on the panel
ENTRY = re.compile(r"(\w+): \{\s*glow: '#([0-9a-fA-F]{6})',\s*path: '([^']+)',", re.S)


def render(path: str) -> bytes:
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">'
           f'<path fill="#fff" d="{path}"/></svg>')
    png = subprocess.run(["rsvg-convert", "-w", str(SIZE), "-h", str(SIZE)],
                         input=svg.encode(), capture_output=True, check=True).stdout
    return Image.open(BytesIO(png)).convert("RGBA").getchannel("A").tobytes()


def main() -> None:
    logos = ENTRY.findall(SOURCE.read_text())
    parts = ["/* Generated by panels/firmware/images/make-logos.py from the hub's Simple Icons\n"
             " * (web/src/lib/brandLogos.ts, CC0): alpha-only logos and their glow colours. */\n"
             '#include "logos.h"\n']
    table = []
    for key, glow, path in logos:
        data = render(path)
        rows = ",\n".join("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24])
                          for i in range(0, len(data), 24))
        parts.append(f"""
static const uint8_t {key}_map[] = {{
{rows}
}};

static const lv_image_dsc_t {key}_logo = {{
    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .w = {SIZE}, .h = {SIZE}, .stride = {SIZE}}},
    .data_size = sizeof({key}_map),
    .data = {key}_map,
}};
""")
        table.append(f'    {{"{key}", &{key}_logo, 0x{glow.lower()}}},')
    parts.append("\nconst logo_t LOGOS[] = {\n" + "\n".join(table) + "\n    {NULL, NULL, 0},\n};\n")
    OUT.write_text("".join(parts))
    print(f"wrote {OUT} with {len(logos)} logos: {', '.join(k for k, _, _ in logos)}")


if __name__ == "__main__":
    main()
